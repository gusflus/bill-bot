#!/usr/bin/env python3
"""Regenerates src/SendersConfig.gs from senders.config.json.

Run this after setup/wizard.py saves a new sender, then `npx clasp push`
to deploy. src/SendersConfig.gs is generated - don't hand-edit it, changes
will be overwritten the next time this runs.
"""
import json
import os

REPO_ROOT = os.path.join(os.path.dirname(__file__), "..")
SENDERS_CONFIG_PATH = os.path.join(REPO_ROOT, "senders.config.json")
OUTPUT_PATH = os.path.join(REPO_ROOT, "src", "SendersConfig.gs")


def js_string_literal(value):
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
    return f"'{escaped}'"


def js_entry(sender):
    fields = [
        f"    name: {js_string_literal(sender['name'])}",
        f"    fromAddress: {js_string_literal(sender['fromAddress'])}",
        f"    matchType: {js_string_literal(sender['matchType'])}",
    ]
    if sender.get("regexSource") is not None:
        fields.append(f"    regexSource: {js_string_literal(sender['regexSource'])}")
    return "  {\n" + ",\n".join(fields) + "\n  }"


def main():
    with open(SENDERS_CONFIG_PATH) as f:
        senders = json.load(f)

    entries = ",\n".join(js_entry(s) for s in senders)
    contents = (
        "// GENERATED by build/generate_senders_config.py from senders.config.json.\n"
        "// Do not hand-edit - your changes will be overwritten. Add senders via\n"
        "// `python setup/wizard.py --sender <address>` instead.\n\n"
        f"const SENDERS = [\n{entries}\n];\n"
    )

    with open(OUTPUT_PATH, "w") as f:
        f.write(contents)

    print(f"Wrote {len(senders)} sender(s) to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
